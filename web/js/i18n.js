const DICT = { ko, en };

function detect() {
  try { const saved = localStorage.getItem(KEY); if (LANGS.includes(saved)) return saved; } catch { /* 저장 불가 환경 */ }
  const first = String((navigator.languages && navigator.languages[0]) || navigator.language || '').toLowerCase();
  return first.startsWith('ko') ? 'ko' : 'en';
}

let lang = detect();
const listeners = new Set();

export const getLang = () => lang;

/** 지금 언어의 문구. 없으면 한국어 문구, 그것도 없으면 키를 그대로 */
export function t(key, params) {
  const v = DICT[lang][key] ?? ko[key] ?? key;
  if (Array.isArray(v) || !params) return v;
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** 번역문을 요소에 넣기: **굵게** 와 \n(줄바꿈)만 DOM으로 만들고 나머지는 글자 그대로 */
export function setRich(el, text) {
  const parts = String(text).split(/(\*\*[^*]+\*\*|\n)/).filter(Boolean);
  el.replaceChildren(...parts.map(p => {
    if (p === '\n') return document.createElement('br');
    if (p.startsWith('**') && p.endsWith('**')) { const b = document.createElement('b'); b.textContent = p.slice(2, -2); return b; }
    return document.createTextNode(p);
  }));
}

/** index.html의 고정 문구 · 문서 언어 · 설명 채우기 */
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  for (const el of root.querySelectorAll('[data-i18n]')) setRich(el, t(el.dataset.i18n));
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.setAttribute('placeholder', t(el.dataset.i18nPh));
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
}

/** 언어 바꾸기 → 저장하고 고정 문구를 다시 채운 뒤, 등록된 화면들에 알림 */
export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* 저장 불가 환경 */ }
  applyStatic();
  for (const fn of listeners) fn(lang);
}
export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
